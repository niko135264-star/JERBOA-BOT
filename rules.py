@commands.slash_command(
    name="правила",
    description="Правила сервера."
)
@commands.has_any_role(*ALLOWED_RULE_ROLES)
async def rules_send(ctx: disnake.ApplicationCommandInteraction):

    await ctx.response.defer(ephemeral=True)

    if (
        not WEBHOOK_URL
        or WEBHOOK_URL == "ВСТАВЬ_НОВЫЙ_WEBHOOK_СЮДА"
    ):
        await ctx.edit_original_message(
            content=(
                "❌ В файле `commands/rules.py` не указан WEBHOOK_URL.\n"
                "Создай новый вебхук и вставь его в переменную "
                "`WEBHOOK_URL`."
            )
        )
        return

    try:
        webhook = disnake.Webhook.from_url(
            WEBHOOK_URL,
            session=ctx.bot.http._HTTPClient__session
        )

        # Первая часть
        await webhook.send(
            content=RULES_PART1,
            username="JERBOA BOT RULES",
            avatar_url=RULES_AVATAR
        )

        # Вторая часть
        await webhook.send(
            content=RULES_PART2,
            username="JERBOA BOT RULES",
            avatar_url=RULES_AVATAR
        )

        await ctx.edit_original_message(
            content="✅ Правила успешно опубликованы через вебхук!"
        )

    except Exception as e:
        print(f"[RULES] Ошибка отправки правил: {e}")

        await ctx.edit_original_message(
            content=f"❌ Не удалось отправить правила.\nОшибка: `{e}`"
        )


# =========================================================
#                    ЗАГРУЗКА EXTENSION
# =========================================================

def setup(bot):
    bot.add_slash_command(rules_send)